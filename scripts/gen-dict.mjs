/*
 * The pronouncing dictionary's data (src/dict/cmudict-data.gen.ts) from the CMU Pronouncing Dictionary
 * (data/cmudict/cmudict.txt.gz: CHIMERA's copy of cmudict.dict, first pronunciations, BSD-style licence
 * in data/cmudict/LICENSE). Only the words the English reader gets wrong without a dictionary are kept:
 * for every other word the reader already says what CMU says, sounds and stress, so the residual and
 * the reader together are the whole dictionary (test/lyrics/dict.test.ts checks every word).
 *
 * Encoding: each ARPAbet phone with its stress is one character (PHONE_CHARS); the words are sorted and
 * front-coded, a line being one character for the length shared with the word before (from '0'), the
 * rest of the word, a tab and the phones. --check fails if the checked-in file is not current.
 */

import { build } from 'esbuild';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { gunzipSync } from 'node:zlib';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const pkg = join(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');

const tmp = mkdtempSync(join(tmpdir(), 'bellows-dict-'));
const outfile = join(tmp, 'reader.mjs');
await build({
  stdin: {
    contents: `export { pronounceEnglish, isHandWord } from './src/lyrics/english';\nexport { arpabetToSegments } from './src/lyrics/arpabet';\nexport { PHONE_CHARS, PHONES } from './src/dict/phones';`,
    resolveDir: pkg,
    loader: 'ts',
  },
  bundle: true,
  format: 'esm',
  platform: 'node',
  outfile,
  external: ['bellowsjs'],
  logLevel: 'error',
});
const { pronounceEnglish, isHandWord, arpabetToSegments, PHONE_CHARS, PHONES } = await import(pathToFileURL(outfile).href);
rmSync(tmp, { recursive: true, force: true });

const charOf = new Map(PHONES.map((p, i) => [p, PHONE_CHARS[i]]));
const key = (segs) => segs.map((s) => s.ipa + (s.stress ?? '')).join(' ');

const text = gunzipSync(readFileSync(join(pkg, 'data/cmudict/cmudict.txt.gz'))).toString('utf8');
const kept = [];
let total = 0;
let skipped = 0;
for (const line of text.split('\n')) {
  const tab = line.indexOf('\t');
  if (tab < 0) continue;
  const word = line.slice(0, tab).trim();
  const arpa = line.slice(tab + 1).trim();
  // the reader strips a word's edge apostrophes before it looks it up ("dancin'", "activists'"), so those
  // entries could never be found
  if (!/^[a-z][a-z']*[a-z]$|^[a-z]$/.test(word)) {
    skipped++;
    continue;
  }
  total++;
  // the reader's own tables win over CMU's (a sung "fire" keeps one syllable), so those are not stored
  if (isHandWord(word)) continue;
  const phones = arpa.split(/\s+/);
  if (phones.some((p) => !charOf.has(p))) {
    skipped++;
    continue;
  }
  if (key(pronounceEnglish(word)) === key(arpabetToSegments(arpa))) continue;
  kept.push([word, phones.map((p) => charOf.get(p)).join('')]);
}
kept.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));
let prev = '';
const lines = [];
for (const [w, ph] of kept) {
  let n = 0;
  while (n < w.length && n < prev.length && n < 40 && w[n] === prev[n]) n++;
  lines.push(String.fromCharCode(48 + n) + w.slice(n) + '\t' + ph);
  prev = w;
}
const data = lines.join('\n');
const out = `/* Generated by scripts/gen-dict.mjs from the CMU Pronouncing Dictionary (data/cmudict/LICENSE). Do not edit. */
/** Words: ${total}; kept (the English reader differs from CMU): ${kept.length}. */
/*! The CMU Pronouncing Dictionary, Copyright (C) 1993-2015 Carnegie Mellon University, BSD-style license: notice in bellows-voice's THIRD_PARTY_NOTICES.md */
export const CMUDICT_WORDS = ${total};
export const CMUDICT_DATA = ${JSON.stringify(data)};
`;
const target = join(pkg, 'src/dict/cmudict-data.gen.ts');
if (check) {
  let cur = '';
  try {
    cur = readFileSync(target, 'utf8');
  } catch {}
  if (cur !== out) {
    console.error('src/dict/cmudict-data.gen.ts is not current: run npm run gen:dict');
    process.exit(1);
  }
  console.log('dictionary up to date');
} else {
  writeFileSync(target, out);
  console.log(`dictionary: ${total} words, ${kept.length} kept (${((100 * kept.length) / total).toFixed(1)} percent), ${skipped} skipped, ${(out.length / 1024).toFixed(0)} KB`);
}
