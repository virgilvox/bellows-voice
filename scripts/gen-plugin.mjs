/*
 * Generates the voice's two build-time sources:
 *
 *   src/worklet-code.gen.ts  the engine as one self-contained IIFE string, the script the plugin
 *                            adds to bellows' worklet (src/worklet-entry.ts, bundled with what it
 *                            imports from bellowsjs)
 *   src/catalog.gen.ts       the engine's description (id, label, params, polyphony), so the main
 *                            thread lists it without loading the DSP
 *
 * Run after any change to the engine or its tables:
 *
 *   node scripts/gen-plugin.mjs           write both
 *   node scripts/gen-plugin.mjs --check   exit 1 if either is stale
 */

import { build } from 'esbuild';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { BANNER } from './banner.mjs';

const pkg = join(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');

const worklet = await build({
  entryPoints: [join(pkg, 'src/worklet-entry.ts')],
  bundle: true,
  format: 'iife',
  target: 'es2022',
  minify: true,
  write: false,
  legalComments: 'none',
  banner: { js: BANNER },
});
const code = worklet.outputFiles[0].text;
const workletOut =
  '/* Generated by scripts/gen-plugin.mjs. Do not edit by hand. */\n' +
  '// prettier-ignore\n' +
  'export const workletCode: string = ' +
  JSON.stringify(code) +
  ';\n';

const dir = mkdtempSync(join(tmpdir(), 'bellows-voice-'));
let catalogOut;
try {
  const file = join(dir, 'engine.mjs');
  await build({
    entryPoints: [join(pkg, 'src/engines/vocal.ts')],
    bundle: true,
    format: 'esm',
    platform: 'node',
    outfile: file,
    logLevel: 'error',
  });
  const { vocalEngine } = await import(pathToFileURL(file).href);
  const info = { id: vocalEngine.id, label: vocalEngine.label, params: vocalEngine.params, polyphony: vocalEngine.polyphony };
  catalogOut =
    '/* Generated by scripts/gen-plugin.mjs from src/engines/vocal.ts. Do not edit by hand. */\n' +
    "import type { EngineInfo } from 'bellowsjs';\n\n" +
    '/** The vocal engine as listEngines() describes it, without its DSP. */\n' +
    '// prettier-ignore\n' +
    'export const VOCAL_ENGINE_INFO: EngineInfo = ' +
    JSON.stringify(info, null, 2) +
    ';\n';
} finally {
  rmSync(dir, { recursive: true, force: true });
}

const targets = [
  [join(pkg, 'src/worklet-code.gen.ts'), workletOut],
  [join(pkg, 'src/catalog.gen.ts'), catalogOut],
];
if (check) {
  const stale = targets.filter(([p, text]) => {
    try {
      return readFileSync(p, 'utf8') !== text;
    } catch {
      return true;
    }
  });
  if (stale.length) {
    console.error('stale: ' + stale.map(([p]) => p).join(', ') + '. Run npm run gen:plugin.');
    process.exit(1);
  }
  console.log('plugin sources up to date');
} else {
  for (const [p, text] of targets) writeFileSync(p, text);
  console.log('worklet script: ' + (code.length / 1024).toFixed(1) + ' KB; catalog: ' + catalogOut.length + ' bytes');
}
